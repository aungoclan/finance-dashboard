export function normalizeCategoryName(value) {
  return String(value || '').trim().toLowerCase()
}

export function getCategoryDisplayName(record) {
  return record?.cashflow_categories?.name || record?.category || 'Uncategorized'
}

export function getCategoryKey(record) {
  if (record?.category_id) return `id:${record.category_id}`

  return `text:${normalizeCategoryName(getCategoryDisplayName(record)) || 'uncategorized'}`
}

export function getCategoryOptionsByType(categories = [], type = 'expense') {
  return categories
    .filter((category) => {
      if (category.is_archived) return false
      return category.type === type || category.type === 'both'
    })
    .sort((a, b) => {
      const groupCompare = String(a.group_name || '').localeCompare(String(b.group_name || ''))
      if (groupCompare !== 0) return groupCompare

      const sortCompare = Number(a.sort_order || 100) - Number(b.sort_order || 100)
      if (sortCompare !== 0) return sortCompare

      return String(a.name || '').localeCompare(String(b.name || ''))
    })
}

export function findCategoryById(categories = [], id) {
  if (!id) return null

  return categories.find((category) => category.id === id) || null
}

export function buildCategoryPayload({ categories, categoryId, customCategory }) {
  const selectedCategory = findCategoryById(categories, categoryId)
  const fallbackCategory = String(customCategory || '').trim()

  if (selectedCategory) {
    return {
      category_id: selectedCategory.id,
      category: selectedCategory.name
    }
  }

  return {
    category_id: null,
    category: fallbackCategory || null
  }
}

export async function ensureDefaultCashflowCategories(supabase, userId) {
  if (!userId) return []

  const { data: existing, error: existingError } = await supabase
    .from('cashflow_categories')
    .select('id, name, name_key, type, group_name, icon, color, is_default, is_archived, sort_order, created_at')
    .eq('user_id', userId)
    .order('sort_order', { ascending: true })
    .order('name', { ascending: true })

  if (existingError) throw existingError

  const existingKeys = new Set((existing || []).map((item) => normalizeCategoryName(item.name)))

  const missingRows = DEFAULT_CASHFLOW_CATEGORIES
    .filter((category) => !existingKeys.has(normalizeCategoryName(category.name)))
    .map((category) => ({
      user_id: userId,
      name: category.name,
      type: category.type,
      group_name: category.group_name,
      icon: category.icon,
      color: category.color,
      is_default: true,
      is_archived: false,
      sort_order: category.sort_order
    }))

  if (missingRows.length > 0) {
    const { error: insertError } = await supabase
      .from('cashflow_categories')
      .upsert(missingRows, {
        onConflict: 'user_id,name_key',
        ignoreDuplicates: true
      })

    if (insertError) throw insertError
  }

  const { data, error } = await supabase
    .from('cashflow_categories')
    .select('id, name, name_key, type, group_name, icon, color, is_default, is_archived, sort_order, created_at')
    .eq('user_id', userId)
    .order('sort_order', { ascending: true })
    .order('name', { ascending: true })

  if (error) throw error

  return data || []
}